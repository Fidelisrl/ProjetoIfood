public class Endereco {

    public String rua;
    public String numero;
    public String bairro;
    public String complemento;

    public Endereco(String rua, String numero, String bairro, String complemento) {
        this.rua = rua;
        this.numero = numero;
        this.bairro = bairro;
        this.complemento = complemento;
    }
}